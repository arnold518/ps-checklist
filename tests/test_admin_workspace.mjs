import assert from 'node:assert/strict';
import fs from 'node:fs';
import {existingDraft,editCell,cellValue,describeChanges} from '../src/adminWorkspaceModel.js';
const contests=JSON.parse(fs.readFileSync(new URL('../problemlists/contestlist.json',import.meta.url)));
const problems=JSON.parse(fs.readFileSync(new URL('../problemlists/problems.json',import.meta.url)));
const catalog={contests,problems,versions:{contests:Object.fromEntries(contests.map(c => [c.id,'c1'])),problems:Object.fromEntries(problems.map(p => [p.id,'p1']))},usages:{}};
const row={status:'editing',draft:existingDraft(contests[0],catalog)};
editCell(row,'year','2020-I');
editCell(row,'contestLabel','Day 1');
editCell(row,'category','ICPC > Regionals > Korea');
editCell(row,'materials.statement','https://example.org/new.pdf');
assert.equal(row.draft.contest.year,'2020-I');
assert.equal(row.draft.contest.contestLabel,'Day 1');
assert.equal(cellValue(row.draft.contest,'category'),'ICPC > Regionals > Korea');
assert.equal(row.draft.contest.id,contests[0].id);
assert.deepEqual(row.draft.contest.problems,contests[0].problems);
assert.equal(row.draft.original.contest.year,'2023');
assert.equal(row.draft.versions.problems[problems[0].id],'p1');
assert.equal(row.draft.contest.materials.find(m => m.role==='editorial').url,contests[0].materials.find(m => m.role==='editorial').url);
assert(describeChanges(row).some(line => line.includes('2020-I')));
assert(describeChanges(row).some(line => line.includes('contestLabel: empty → Day 1')));
editCell(row,'contestLabel','');
assert(!Object.hasOwn(row.draft.contest,'contestLabel'));
console.log('Workspace model: textual years, explicit overrides, stable IDs, memberships, and original versions passed.');
